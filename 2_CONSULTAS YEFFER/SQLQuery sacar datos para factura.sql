                      A.REMISION
FROM         Trade AS A INNER JOIN
                      MVTRADE AS B ON A.NRODCTO = B.NRODCTO AND A.TIPODCTO = B.TIPODCTO INNER JOIN
                      VENDEN AS C ON A.CODVEN = C.CODVEN INNER JOIN
                      MTPROCLI AS D ON A.NIT = D.NIT INNER JOIN
                      MTMERCIA AS E ON B.PRODUCTO = E.CODIGO

SELECT     A.BODEGA, B.CODGRUPO, C.NOMBRE, A.CODIGO,B.CODBARRAS, B.DESCRIPCIO, A.NIT,  D.NOMBRE, SUM(A.ICANTIDAD - A.OCANTIDAD) 
FROM         SALDOINV A INNER JOIN
                      MTMERCIA B ON A.CODIGO = B.CODIGO INNER JOIN
                      MTGRUINV C ON B.CODGRUPO = C.CODGRUPO INNER JOIN
                      MTPROCLI D ON A.NIT = D.NIT
WHERE     (A.BODEGA LIKE ('%PT%'))
GROUP BY A.BODEGA, B.CODGRUPO, C.NOMBRE, A.CODIGO, B.CODBARRAS, B.DESCRIPCIO, A.NIT, D.NOMBRE
ORDER BY C.NOMBRE, B.DESCRIPCIO

